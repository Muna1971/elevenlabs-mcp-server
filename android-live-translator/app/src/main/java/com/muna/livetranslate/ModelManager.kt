package com.muna.livetranslate

import android.content.Context
import com.google.mlkit.common.model.DownloadConditions
import com.google.mlkit.nl.translate.TranslateLanguage
import com.google.mlkit.nl.translate.Translation
import com.google.mlkit.nl.translate.Translator
import com.google.mlkit.nl.translate.TranslatorOptions
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.tasks.await
import kotlinx.coroutines.withContext
import org.json.JSONObject
import java.io.File
import java.io.IOException
import java.io.InputStream
import java.net.HttpURLConnection
import java.net.URL
import java.util.zip.GZIPInputStream

/** Downloads (once) and locates the offline models. */
object ModelManager {

    private const val HF = "https://huggingface.co"
    private const val WHISPER_FAST = "ggml-tiny-q5_1.bin"
    private const val WHISPER_ACCURATE = "ggml-base-q5_1.bin"
    private const val VAD_MODEL = "ggml-silero-v6.2.0.bin"

    fun speechModelUrl(accurate: Boolean) =
        "$HF/ggerganov/whisper.cpp/resolve/main/${if (accurate) WHISPER_ACCURATE else WHISPER_FAST}"
    const val VAD_MODEL_URL = "$HF/ggml-org/whisper-vad/resolve/main/$VAD_MODEL"

    fun speechModelFile(context: Context, accurate: Boolean) =
        File(context.filesDir, if (accurate) WHISPER_ACCURATE else WHISPER_FAST)
    fun vadModelFile(context: Context) = File(context.filesDir, VAD_MODEL)

    fun isSpeechReady(context: Context, accurate: Boolean) =
        speechModelFile(context, accurate).exists() && vadModelFile(context).exists()

    suspend fun downloadSpeechModels(context: Context, accurate: Boolean, onProgress: (Int) -> Unit) {
        if (!vadModelFile(context).exists()) download(VAD_MODEL_URL, vadModelFile(context), gunzip = false) {}
        val model = speechModelFile(context, accurate)
        if (!model.exists()) download(speechModelUrl(accurate), model, gunzip = false, onProgress)
    }

    // --- Mozilla Bergamot translation models (catalog generated by tools/make_bergamot_catalog.py) ---

    class PairFiles(val dir: File, val model: File, val vocab: File, val lex: File, val targetVocab: File?)

    private var catalog: JSONObject? = null

    private fun catalog(context: Context): JSONObject = catalog ?: JSONObject(
        context.assets.open("bergamot_models.json").bufferedReader().use { it.readText() }
    ).also { catalog = it }

    fun hasBergamotPair(context: Context, pair: String) = catalog(context).getJSONObject("pairs").has(pair)

    fun bergamotFiles(context: Context, pair: String): PairFiles {
        val dir = File(context.filesDir, "bergamot/$pair")
        val hasTargetVocab = catalog(context).getJSONObject("pairs").getJSONObject(pair).has("trgVocab")
        return PairFiles(
            dir, File(dir, "model.bin"), File(dir, "vocab.spm"), File(dir, "lex.bin"),
            if (hasTargetVocab) File(dir, "trgvocab.spm") else null,
        )
    }

    fun isBergamotReady(context: Context, pair: String) =
        File(bergamotFiles(context, pair).dir, READY_MARKER).exists()

    suspend fun downloadBergamot(context: Context, pair: String, onProgress: (Int) -> Unit = {}) {
        if (isBergamotReady(context, pair)) return
        val root = catalog(context)
        val entry = root.getJSONObject("pairs").getJSONObject(pair)
        val base = root.getString("baseUrl")
        val files = bergamotFiles(context, pair)
        files.dir.mkdirs()
        download("$base/${entry.getString("vocab")}", files.vocab, gunzip = true) {}
        files.targetVocab?.let { download("$base/${entry.getString("trgVocab")}", it, gunzip = true) {} }
        download("$base/${entry.getString("lex")}", files.lex, gunzip = true) {}
        download("$base/${entry.getString("model")}", files.model, gunzip = true, onProgress)
        File(files.dir, READY_MARKER).writeText("ok")
    }

    // --- Google ML Kit, only for languages Mozilla has no model for ---

    fun mlKitLanguage(code: String): String? = TranslateLanguage.fromLanguageTag(code)

    fun newMlKitArabicTranslator(sourceMlKitLanguage: String): Translator = Translation.getClient(
        TranslatorOptions.Builder()
            .setSourceLanguage(sourceMlKitLanguage)
            .setTargetLanguage(TranslateLanguage.ARABIC)
            .build()
    )

    suspend fun ensureDownloaded(translator: Translator) {
        translator.downloadModelIfNeeded(DownloadConditions.Builder().build()).await()
    }

    private suspend fun download(url: String, dest: File, gunzip: Boolean, onProgress: (Int) -> Unit) =
        withContext(Dispatchers.IO) {
            val part = File(dest.path + ".part")
            val conn = URL(url).openConnection() as HttpURLConnection
            conn.connectTimeout = 20_000
            conn.readTimeout = 30_000
            try {
                if (conn.responseCode !in 200..299) throw IOException("HTTP ${conn.responseCode}")
                val total = conn.contentLengthLong
                val counting = CountingStream(conn.inputStream)
                val input: InputStream = if (gunzip) GZIPInputStream(counting, 64 * 1024) else counting
                input.use { stream ->
                    part.outputStream().use { out ->
                        val buf = ByteArray(64 * 1024)
                        var lastPercent = -1
                        while (true) {
                            val n = stream.read(buf)
                            if (n < 0) break
                            out.write(buf, 0, n)
                            if (total > 0) {
                                val percent = (counting.count * 100 / total).toInt()
                                if (percent != lastPercent) {
                                    lastPercent = percent
                                    withContext(Dispatchers.Main) { onProgress(percent) }
                                }
                            }
                        }
                    }
                }
                if (!gunzip && total > 0 && counting.count != total) throw IOException("Download incomplete")
            } finally {
                conn.disconnect()
            }
            if (!part.renameTo(dest)) throw IOException("Could not save ${dest.name}")
        }

    private class CountingStream(private val inner: InputStream) : InputStream() {
        var count = 0L
            private set
        override fun read(): Int = inner.read().also { if (it >= 0) count++ }
        override fun read(b: ByteArray, off: Int, len: Int): Int =
            inner.read(b, off, len).also { if (it > 0) count += it }
        override fun close() = inner.close()
    }

    private const val READY_MARKER = ".ready"
}
